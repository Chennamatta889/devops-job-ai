-- DraftflowAI production user data model.
-- Apply this only to a Supabase project dedicated to DraftflowAI.

create table if not exists public.candidate_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null default '',
  email text not null default '',
  phone text not null default '',
  linkedin text not null default '',
  current_location text not null default '',
  current_company text not null default '',
  years_experience numeric(4,1) not null default 0,
  target_roles text[] not null default '{}',
  skills text[] not null default '{}',
  preferred_locations text[] not null default '{India}',
  current_ctc_lpa numeric(8,2),
  expected_ctc_lpa numeric(8,2),
  notice_period_days integer,
  education text not null default '',
  university text not null default '',
  degree_specialization text not null default '',
  graduation_year integer,
  willing_to_relocate boolean,
  willing_to_work_in_shifts boolean,
  willing_to_work_on_call boolean,
  open_to_remote boolean,
  open_to_hybrid boolean,
  open_to_onsite boolean,
  requires_us_visa_sponsorship boolean,
  can_provide_india_right_to_work_proof boolean,
  willing_to_take_assessments boolean,
  minimum_match_score integer not null default 80 check (minimum_match_score between 50 and 100),
  daily_application_limit integer not null default 10 check (daily_application_limit between 1 and 100),
  auto_apply_enabled boolean not null default false,
  consent_version text not null default '',
  consented_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.screening_answers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question text not null,
  answer jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, question)
);

create table if not exists public.resume_variants (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  filename text not null,
  storage_path text not null unique,
  content_type text not null default 'application/pdf',
  resume_text text not null default '',
  target_roles text[] not null default '{}',
  skills text[] not null default '{}',
  years_experience numeric(4,1) not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.application_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  external_job_id text not null,
  source text not null default '',
  title text not null,
  company text not null,
  location text not null default '',
  apply_url text not null,
  match_score numeric(5,2) not null default 0,
  status text not null default 'QUEUED',
  message text not null default '',
  confirmation text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, external_job_id)
);

create index if not exists application_attempts_status_created_idx
  on public.application_attempts (status, created_at);
create index if not exists resume_variants_user_active_idx
  on public.resume_variants (user_id, active, updated_at desc);

