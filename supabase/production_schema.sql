-- The private "resumes" bucket is created through the Storage API by
-- auto_apply/supabase_worker.py. Do not write bucket/object metadata directly.

drop policy if exists "resume_objects_select_own" on storage.objects;
create policy "resume_objects_select_own" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'resumes'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "resume_objects_insert_own" on storage.objects;
create policy "resume_objects_insert_own" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'resumes'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "resume_objects_update_own" on storage.objects;
create policy "resume_objects_update_own" on storage.objects
  for update to authenticated
  using (
    bucket_id = 'resumes'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'resumes'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "resume_objects_delete_own" on storage.objects;
create policy "resume_objects_delete_own" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'resumes'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );
